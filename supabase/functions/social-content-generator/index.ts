// supabase/functions/social-content-generator/index.ts
//
// Generates social posts (LinkedIn/Telegram) for BidDeed.AI content, unattended.
// Zero human review by design -- but zero free-form number generation too.
// Every figure in the output is pulled straight from multi_county_auctions;
// the LLM (if used at all) only writes surrounding prose around numbers it
// is handed, never numbers it invents. Deduplicated via content_hash so the
// same county/day/platform never queues twice.
//
// Runs on a schedule (GHA cron -> POST this function). Writes to
// social_content_queue with status='pending'; separate publish workers
// (social-publish-worker for LinkedIn, social-publish-worker-telegram for
// Telegram) read pending rows for their platform and post them.
//
// NOTE (issue #19088): committed to the repo as-is for traceability -- this
// file is unmodified from what is deployed. property-spotlight content
// (source_type='property_spotlight') is generated by a separate script and
// does not touch this generator, per that issue's non-goals.

import { createClient } from "https://esm.sh/@supabase/supabase-js@2.45.0";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const CORS = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Methods": "POST, OPTIONS" };
function jsonRes(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json", ...CORS } });
}

async function sha256Hex(input: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(input));
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function vaultSecret(name: string): Promise<string | null> {
  const { data, error } = await supabase.rpc("vault_secret", { p_name: name });
  if (!error && data) return String(data);
  return null;
}

async function alertFailure(context: string, detail: string) {
  try {
    const token = await vaultSecret("telegram_bot_token");
    const chatId = await vaultSecret("telegram_chat_id");
    if (!token || !chatId) return;
    await fetch(`https://api.telegram.org/bot${token}/sendMessage`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        chat_id: chatId,
        text: `\u{1F6A8} social-content-generator failed\n${context}\n${detail}`.slice(0, 4000),
      }),
    });
  } catch (_) { /* alerting must never throw */ }
}

// Blog slugs are hardcoded here, NOT derived from a formula -- an earlier
// version guessed the slug pattern (fc>td ? 'foreclosure' : 'tax-deed') and
// got it wrong for Escambia and Marion, which don't follow that pattern.
// Caught in testing before anything published. Add new counties here when
// their blog post ships; never derive.
const BLOG_SLUGS: Record<string, string> = {
  putnam: "putnam-county-tax-deed-auctions-guide",
  escambia: "escambia-county-foreclosure-auction-guide",
  highlands: "highlands-county-tax-deed-auctions-guide",
  marion: "marion-county-foreclosure-auctions-guide",
};

// Template-only content -- no field here is ever LLM-generated. Every
// ${...} is a literal value pulled from the auction row. Same plain-text
// content is used for both LinkedIn and Telegram -- both render plain text
// fine, and reusing one template avoids a second place for a slug/formula
// bug to hide (see BLOG_SLUGS comment above -- that bug taught this lesson).
function buildPostContent(county: string, countyLabel: string, stats: {
  upcoming: number; td: number; fc: number; avgOpening: number; avgAssessed: number;
}) {
  const spread = stats.avgAssessed - stats.avgOpening;
  const spreadLine = spread > 0
    ? `Average spread between opening bid and assessed value: $${spread.toLocaleString()}.`
    : `Note: average opening bid ($${stats.avgOpening.toLocaleString()}) currently runs ABOVE average assessed value ($${stats.avgAssessed.toLocaleString()}) in this county -- worth screening lots individually rather than assuming a discount.`;

  const blogSlug = BLOG_SLUGS[county];
  const linkLine = blogSlug
    ? `Full breakdown: https://biddeed.ai/blog/${blogSlug}`
    : `Full breakdown: https://biddeed.ai/county/${county}`;

  return [
    `${countyLabel} County, FL -- current auction pipeline snapshot:`,
    ``,
    `${stats.upcoming} upcoming lots (${stats.fc} foreclosure, ${stats.td} tax deed).`,
    `Average opening bid: $${stats.avgOpening.toLocaleString()}`,
    `Average assessed value: $${stats.avgAssessed.toLocaleString()}`,
    spreadLine,
    ``,
    linkLine,
    ``,
    `Informational only -- not legal, financial, or investment advice. Verify independently before bidding.`,
  ].join("\n");
}

const PLATFORMS = ["linkedin_personal", "telegram"] as const;

async function queueOne(platform: string, countySlug: string, content: string, todayKey: string) {
  // Idempotency hash. IMPORTANT: linkedin_personal's hash format is kept
  // byte-for-byte identical to the original single-platform version
  // (sha256(todayKey), no platform prefix) so it stays compatible with rows
  // already sitting in the queue from earlier testing -- prefixing it here
  // would have made the generator think today's already-queued LinkedIn
  // content was "new" and insert duplicate rows alongside the pending ones.
  // Caught this before deploying by checking the table's actual state.
  // telegram is a brand-new platform with no existing rows, so it safely
  // gets a platform-prefixed hash to keep it namespaced from LinkedIn's.
  const contentHash = platform === "linkedin_personal"
    ? await sha256Hex(todayKey)
    : await sha256Hex(`${platform}|${todayKey}`);

  const { data: existing } = await supabase
    .from("social_content_queue")
    .select("id")
    .eq("content_hash", contentHash)
    .limit(1);
  if (existing && existing.length > 0) {
    return { ok: true, skipped: true, reason: `duplicate content_hash for ${platform}, already queued` };
  }

  const { error: insertErr } = await supabase.from("social_content_queue").insert({
    content_hash: contentHash,
    target_platform: platform,
    source_type: "county_snapshot",
    source_ref: countySlug,
    content_text: content,
    status: "pending",
  });
  if (insertErr) {
    return { ok: false, reason: `insert failed for ${platform}: ${insertErr.message}` };
  }
  return { ok: true, skipped: false, contentHash };
}

async function generateForCounty(countySlug: string, countyLabel: string) {
  const { data: rows, error } = await supabase
    .from("multi_county_auctions")
    .select("opening_bid,assessed_value,sale_type")
    .eq("county", countySlug)
    .eq("auction_status", "upcoming")
    .gte("auction_date", new Date().toISOString().slice(0, 10));

  if (error || !rows || rows.length === 0) {
    return { ok: false, reason: `no upcoming rows for ${countySlug}: ${error?.message ?? "empty"}` };
  }

  const upcoming = rows.length;
  const fc = rows.filter((r: any) => r.sale_type === "foreclosure").length;
  const td = rows.filter((r: any) => r.sale_type === "tax_deed").length;
  const validOpening = rows.map((r: any) => Number(r.opening_bid)).filter((n: number) => Number.isFinite(n) && n > 0);
  const validAssessed = rows.map((r: any) => Number(r.assessed_value)).filter((n: number) => Number.isFinite(n) && n > 0);
  if (validOpening.length === 0 || validAssessed.length === 0) {
    return { ok: false, reason: `${countySlug} has no usable opening_bid/assessed_value rows` };
  }
  const avgOpening = Math.round(validOpening.reduce((a: number, b: number) => a + b, 0) / validOpening.length);
  const avgAssessed = Math.round(validAssessed.reduce((a: number, b: number) => a + b, 0) / validAssessed.length);

  const content = buildPostContent(countySlug, countyLabel, { upcoming, td, fc, avgOpening, avgAssessed });
  const today = new Date().toISOString().slice(0, 10);
  const todayKey = `${countySlug}|${today}|${upcoming}|${avgOpening}|${avgAssessed}`;

  const platformResults: Record<string, any> = {};
  for (const platform of PLATFORMS) {
    platformResults[platform] = await queueOne(platform, countySlug, content, todayKey);
  }
  const anyFailed = Object.values(platformResults).some((r: any) => !r.ok);
  return { ok: !anyFailed, platforms: platformResults };
}

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: CORS });
  if (req.method !== "POST") return jsonRes({ error: "POST required" }, 405);

  let body: any = {};
  try { body = await req.json(); } catch (_) { /* empty body is fine, use defaults */ }

  // Default set: the 4 counties with published guides. Extendable via body.counties.
  const counties: [string, string][] = body.counties ?? [
    ["putnam", "Putnam"],
    ["escambia", "Escambia"],
    ["highlands", "Highlands"],
    ["marion", "Marion"],
  ];

  const results = [];
  for (const [slug, label] of counties) {
    try {
      const r = await generateForCounty(slug, label);
      results.push({ county: slug, ...r });
      if (!r.ok) await alertFailure(`generateForCounty(${slug})`, JSON.stringify(r.platforms ?? r));
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      results.push({ county: slug, ok: false, reason: `threw: ${msg}` });
      await alertFailure(`generateForCounty(${slug}) threw`, msg);
    }
  }

  return jsonRes({ ok: true, results });
});
