-- template ("bolt32"). Additive only, per M2/M5 -- no existing column
-- dropped or retyped, no row touched by this migration itself.
--
-- 1. winnerdata.biddeed_reels gains bolt32-specific columns. The issue's
--    literal list is `template text, title_candidates jsonb, title_chosen
--    text, beat_map jsonb, loop_frame_ms int`. Two columns beyond that list
--    are added and logged here as a deviation: `video_bolt32_url` and
--    `duration_bolt32_sec`. Neither v1's `video_url`, v2's `video_v2_url`,
--    nor presale's reuse of `video_v2_url` is safe to overwrite in place for
