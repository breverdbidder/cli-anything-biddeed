-- ---------------------------------------------------------------------
-- Watch-progress event RPC
-- ---------------------------------------------------------------------
create or replace function public.log_reel_watch_event(
  p_code text, p_event text, p_session_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, winnerdata
as $$
declare
  v_reel_id uuid;
  v_pct numeric;
  v_session text;
begin
  if p_event not in ('play', '25', '50', '75', '100', 'loop') then
    return jsonb_build_object('ok', false, 'error', 'invalid_event');
  end if;

  select id into v_reel_id from winnerdata.biddeed_reels where short_code = p_code limit 1;
  if v_reel_id is null then
    return jsonb_build_object('ok', false, 'error', 'unknown_code');
  end if;

  -- Numeric watch-pct proxy for percentile math in v_reel_retention below:
  -- play=0, 25/50/75/100 literal, loop=125 (a completed rewatch signal,
  -- deliberately > 100 so a loop always outranks a bare "reached 100%" in a
  -- percentile_cont(0.5) computation -- the CP4 gate cares about looping,
  -- not just finishing once).
  v_pct := case p_event when 'play' then 0 when 'loop' then 125 else p_event::numeric end;
  v_session := coalesce(p_session_id, gen_random_uuid()::text);

  insert into winnerdata.funnel_events (session_id, step, params)
  values (
    v_session, 'reel_watch_pct',
    jsonb_build_object('reel_id', v_reel_id, 'code', p_code, 'event', p_event, 'pct_value', v_pct)
  );

  return jsonb_build_object('ok', true);
end;
$$;

grant execute on function public.log_reel_watch_event(text, text, text) to anon, authenticated, service_role;

-- ---------------------------------------------------------------------
-- Retention view (CP4 factory-gate input)
-- ---------------------------------------------------------------------
create or replace view winnerdata.v_reel_retention
with (security_invoker = true) as
select
  r.id as reel_id,
  r.case_number,
  r.county,
  r.phase,
  r.template,
  r.short_code,
  count(*) filter (where fe.params ->> 'event' = 'play') as plays,
  percentile_cont(0.5) within group (order by (fe.params ->> 'pct_value')::numeric) as p50_watch_pct,
  count(*) filter (where fe.params ->> 'event' = 'loop') as loop_count,
  case
    when count(*) filter (where fe.params ->> 'event' = 'play') > 0
      then round(
        100.0 * count(*) filter (where fe.params ->> 'event' = 'loop')
        / count(*) filter (where fe.params ->> 'event' = 'play'), 1
      )
    else null
  end as loop_rate_pct
from winnerdata.biddeed_reels r
left join winnerdata.funnel_events fe
  on fe.step = 'reel_watch_pct' and (fe.params ->> 'reel_id')::uuid = r.id
group by r.id, r.case_number, r.county, r.phase, r.template, r.short_code;

