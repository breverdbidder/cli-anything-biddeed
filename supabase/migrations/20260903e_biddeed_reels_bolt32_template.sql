--    destroy the existing approved-pending v2 asset for a row this issue
--    does not own outright) -- a template needs its own asset pointer to
--    coexist with whatever edit_version already lives on the row.
-- 2. `public.log_reel_watch_event()` -- SECURITY DEFINER RPC the /reels
--    player calls (client-side, anon) to record play/25/50/75/100/loop
--    watch-progress events into winnerdata.funnel_events (pre-existing,
--    0 rows, empty since creation -- confirmed live this session -- so this
--    is the table's first real writer, not a repurposing of live data).
--    event is allow-listed server-side, never free text from the client.
-- 3. `winnerdata.v_reel_retention` -- per-reel plays / p50 watch-through /
--    loop rate, the CP4 factory-gate input ("promotable only if p50
--    watch-through >= 100% on >= 20 plays"). security_invoker=true per M2;
--    no anon/authenticated grant -- read via the Management API, same
--    access pattern every other winnerdata.* read in this pipeline already
--    uses (winnerdata is not PostgREST-exposed on this project).

