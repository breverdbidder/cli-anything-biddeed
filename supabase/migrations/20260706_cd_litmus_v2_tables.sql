CREATE TABLE IF NOT EXISTS public.cd_litmus_parity_v2 (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  county_slug   text NOT NULL,
  source        text NOT NULL,
  sale_type     text NOT NULL,
  window_start  date,
  window_end    date,
  source_count  integer,
  our_count     integer,
  match_pct     numeric,
  fetched_at    timestamptz NOT NULL DEFAULT now(),
  status        text NOT NULL DEFAULT 'ok',
  notes         text
);

CREATE INDEX IF NOT EXISTS idx_cd_litmus_parity_v2_county
  ON public.cd_litmus_parity_v2 (county_slug, source, sale_type, fetched_at DESC);

COMMENT ON TABLE public.cd_litmus_parity_v2 IS
  'C/D LITMUS V2 per-county source-count parity rows. source=realauction|floridabidder|'
  'propertyonion, status=ok|unreachable|off_platform. Count/coverage litmus only — NEVER '
  'a row-level match source; row-level C/D matching still comes from parity_status/'
  'parity_source on multi_county_auctions (see pencil_dod_evaluate_county).';
