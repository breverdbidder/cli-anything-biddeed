CREATE TABLE IF NOT EXISTS public.cd_litmus_hierarchy (
  priority          integer NOT NULL,
  source_slug       text NOT NULL,
  role              text NOT NULL,
  fc_url_template   text,
  td_url_template   text,
  usage_constraint  text NOT NULL,
  constitutional    boolean NOT NULL DEFAULT true,
  directive         text NOT NULL DEFAULT 'Ariel Shapira, 2026-07-06',
  created_at        timestamptz DEFAULT now(),
  CONSTRAINT cd_litmus_hierarchy_pkey PRIMARY KEY (priority),
  CONSTRAINT cd_litmus_hierarchy_source_slug_key UNIQUE (source_slug)
);

COMMENT ON TABLE public.cd_litmus_hierarchy IS
  'Constitutional SSOT (docs/CD-LITMUS-HIERARCHY-V2.md): calendar-parity litmus '
  'source ordering. priority 1=realauction (primary), 2=floridabidder (fallback), '
  '3=propertyonion (tertiary cross-check only, never blocking). Evaluators read '
  'this table to pick which cd_litmus_parity_v2 row is authoritative per county.';

