-- ── skill_evolution_signals ────────────────────────────────────────────────
-- Detected signals that may warrant SKILL.md evolution.
-- signal_type: execution_failure | user_correction | score_regression | sentinel_alert
-- (score_regression + sentinel_alert are NEW vs JiuwenClaw)

CREATE TABLE IF NOT EXISTS skill_evolution_signals (
    id              UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    signal_type     TEXT NOT NULL CHECK (signal_type IN (
                        'execution_failure',
                        'user_correction',
                        'score_regression',
                        'sentinel_alert'
                    )),
    skill_name      TEXT NOT NULL,
    excerpt         TEXT NOT NULL,
    tool_name       TEXT,
    source          TEXT NOT NULL DEFAULT 'session_log'
                        CHECK (source IN ('session_log', 'eval_runner', 'sentinel', 'manual')),
    fingerprint     TEXT NOT NULL,
    created_at      TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    processed       BOOLEAN DEFAULT FALSE NOT NULL,
    UNIQUE(fingerprint)
);

CREATE INDEX IF NOT EXISTS idx_evolution_signals_skill
    ON skill_evolution_signals(skill_name);

CREATE INDEX IF NOT EXISTS idx_evolution_signals_processed
    ON skill_evolution_signals(processed)
    WHERE processed = FALSE;

CREATE INDEX IF NOT EXISTS idx_evolution_signals_type
    ON skill_evolution_signals(signal_type);

-- RLS: service role only
ALTER TABLE skill_evolution_signals ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Service role full access on skill_evolution_signals"
    ON skill_evolution_signals
    FOR ALL
    USING (auth.role() = 'service_role');


-- ── skill_evolution_entries ────────────────────────────────────────────────
-- Proposed SKILL.md patches generated by the LLM evolver.
-- BEATS JiuwenClaw: adds eval_score_before/after, llm_model_used, token_cost

CREATE TABLE IF NOT EXISTS skill_evolution_entries (
    id                  UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    skill_name          TEXT NOT NULL,
    source_signal_id    UUID REFERENCES skill_evolution_signals(id) ON DELETE SET NULL,
    target              TEXT NOT NULL,
    section             TEXT NOT NULL CHECK (section IN (
                            'Instructions',
                            'Examples',
                            'Troubleshooting',
                            'EdgeCases'
                        )),
    content             TEXT NOT NULL,
    action              TEXT NOT NULL DEFAULT 'add' CHECK (action IN ('add', 'update', 'delete', 'skip')),
    skip_reason         TEXT,
    merge_target        TEXT,
    applied             BOOLEAN DEFAULT FALSE NOT NULL,
    eval_score_before   FLOAT,
    eval_score_after    FLOAT,
    llm_model_used      TEXT,
    token_cost          FLOAT,
    created_at          TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_evolution_entries_skill
    ON skill_evolution_entries(skill_name);

CREATE INDEX IF NOT EXISTS idx_evolution_entries_applied
    ON skill_evolution_entries(applied)
    WHERE applied = FALSE;

-- RLS: service role only
ALTER TABLE skill_evolution_entries ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Service role full access on skill_evolution_entries"
    ON skill_evolution_entries
    FOR ALL
    USING (auth.role() = 'service_role');


